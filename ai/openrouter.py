import json
import re
import urllib.request
import urllib.error
from typing import Dict, Any, Optional, Tuple

from ai.prompts import SYSTEM_PROMPT_EN, SYSTEM_PROMPT_BN
from engine.config import get_config_value

OPENROUTER_URL = "https://openrouter.ai/api/v1/chat/completions"

POPULAR_MODELS = [
    {"id": "google/gemini-2.0-flash-001", "name": "Google Gemini 2.0 Flash (Fast & Low Cost)"},
    {"id": "google/gemini-flash-1.5", "name": "Google Gemini 1.5 Flash"},
    {"id": "anthropic/claude-3.5-haiku", "name": "Anthropic Claude 3.5 Haiku"},
    {"id": "meta-llama/llama-3.3-70b-instruct", "name": "Meta Llama 3.3 70B Instruct"},
    {"id": "mistralai/mistral-small-24b-instruct-2501", "name": "Mistral Small 24B"},
]


class OpenRouterClient:
    def __init__(self, api_key: Optional[str] = None, model: Optional[str] = None):
        self.api_key = api_key or get_config_value("openrouter_api_key", "")
        self.model = model or get_config_value("openrouter_model", "google/gemini-2.0-flash-001")
        self.timeout = 60

    def test_connection(self) -> Tuple[bool, str]:
        """Tests whether the configured OpenRouter API key and connection are valid."""
        if not self.api_key:
            return False, "No OpenRouter API key configured. Please configure your key in settings."

        payload = {
            "model": self.model,
            "messages": [{"role": "user", "content": "Respond with 'SUNSCAN_OK'"}],
            "max_tokens": 10,
        }
        data_bytes = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            OPENROUTER_URL,
            data=data_bytes,
            headers={
                "Authorization": f"Bearer {self.api_key}",
                "HTTP-Referer": "https://github.com/codesun/sunscan",
                "X-Title": "SUNSCAN Cybersecurity Toolkit",
                "Content-Type": "application/json",
            },
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=15) as resp:
                if resp.status == 200:
                    return True, f"Connection successful! Model '{self.model}' responded OK."
                return False, f"OpenRouter returned status {resp.status}"
        except urllib.error.HTTPError as e:
            if e.code == 401:
                return False, "Authentication failed. Invalid OpenRouter API key."
            elif e.code == 402:
                return False, "Insufficient credits on OpenRouter account."
            return False, f"OpenRouter API error (HTTP {e.code}): {e.reason}"
        except urllib.error.URLError as e:
            return False, f"Connection error: {e.reason}"
        except Exception as e:
            return False, f"Connection error: {str(e)}"

    def analyze_scan_output(
        self,
        tool_name: str,
        target: str,
        raw_output: str,
        language: str = "en",
    ) -> Tuple[bool, Dict[str, Any], str]:
        """
        Sends the scan output to OpenRouter for structured security interpretation.
        Returns: (success, parsed_json_dict, raw_or_error_message)
        """
        if not self.api_key:
            return False, {}, "OpenRouter API key is not configured. Set it in SUNSCAN settings or env."

        trimmed_output = raw_output
        if len(raw_output) > 25000:
            trimmed_output = raw_output[:25000] + "\n...[Output truncated to 25k characters]..."

        system_prompt = SYSTEM_PROMPT_BN if language == "bn" else SYSTEM_PROMPT_EN

        user_content = (
            f"Please analyze the following raw scan output generated by '{tool_name}' against target '{target}':\n\n"
            f"```\n{trimmed_output}\n```\n\n"
            f"Adhere strictly to the required JSON schema without any markdown wrapping."
        )

        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_content},
            ],
            "temperature": 0.2,
        }
        data_bytes = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            OPENROUTER_URL,
            data=data_bytes,
            headers={
                "Authorization": f"Bearer {self.api_key}",
                "HTTP-Referer": "https://github.com/codesun/sunscan",
                "X-Title": "SUNSCAN Cybersecurity Toolkit",
                "Content-Type": "application/json",
            },
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                res_body = resp.read().decode("utf-8")
                data = json.loads(res_body)
                choices = data.get("choices", [])
                if not choices:
                    return False, {}, "Empty response received from OpenRouter."

                reply_text = choices[0].get("message", {}).get("content", "").strip()
                parsed = self._extract_json(reply_text)
                if parsed:
                    return True, parsed, reply_text
                return False, {}, f"Failed to parse structured JSON from model response: {reply_text[:300]}"

        except urllib.error.HTTPError as e:
            err_body = e.read().decode("utf-8", errors="ignore")
            return False, {}, f"OpenRouter API error (HTTP {e.code}): {err_body[:250]}"
        except urllib.error.URLError as e:
            return False, {}, f"OpenRouter network error: {e.reason}"
        except Exception as e:
            return False, {}, f"OpenRouter request failed: {str(e)}"

    def _extract_json(self, text: str) -> Optional[Dict[str, Any]]:
        cleaned = re.sub(r"^```(?:json)?\s*", "", text.strip(), flags=re.IGNORECASE)
        cleaned = re.sub(r"\s*```$", "", cleaned)
        try:
            return json.loads(cleaned)
        except Exception:
            match = re.search(r"(\{.*\})", text, re.DOTALL)
            if match:
                try:
                    return json.loads(match.group(1))
                except Exception:
                    pass
            return None
